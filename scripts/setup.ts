#!/usr/bin/env node
/**
 * Setup wizard for github-admin-mcp. This script helps you configure the environment by
 * creating a .env file containing your GitHub personal access token. Run it with
 * `npm run setup` from the repository root.
 */
import fs from 'fs';
import path from 'path';
import readline from 'readline';

async function main() {
  console.log('GitHub Admin MCP Setup');
  console.log('This wizard will create a .env file with your GitHub Personal Access Token.');
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  const question = (q: string) => new Promise<string>((resolve) => rl.question(q, resolve));
  try {
    const token = (await question('Enter your GitHub Personal Access Token: ')).trim();
    if (!token) {
      console.error('No token provided. Exiting without creating .env file.');
      rl.close();
      return;
    }
    const envPath = path.join(process.cwd(), '.env');
    const envContent = `# Auto-generated by github-admin-mcp setup script\nGITHUB_TOKEN=${token}\n`;
    fs.writeFileSync(envPath, envContent, { encoding: 'utf8' });
    console.log(`.env file created at ${envPath}.`);
    console.log('You can now run the MCP using your configured token.');
  } catch (err) {
    console.error('Error during setup:', err);
  } finally {
    rl.close();
  }
}

main().catch((err) => console.error(err));